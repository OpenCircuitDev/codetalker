"""
Session — the canonical domain model for a Claude Code session.

This replaces 9 different shapes that previously represented "a session":

  1. SessionState dataclass (in-memory)
  2. persistent_sessions YAML file
  3. resolve_for_session result dict
  4. state.cfg + session deep-merge
  5. companion_active_sessions set membership
  6. /api/sessions response row
  7. /api/companion/sessions response row
  8. Pro Android SessionLite Kotlin class
  9. webui Session TypeScript type

After this refactor, the daemon's SessionStore (phase 1) returns Session
instances from a single SQLite-backed source. The API row builders
(phase 3) project Session into SessionView. Both webui and Pro Android
consume SessionView via codegen'd types (phase 5). End of drift.
"""
from __future__ import annotations

from typing import List, Literal, Optional

from pydantic import BaseModel, Field

from .character import CharacterRef
from .enums import AudioOutput, Cadence, SessionLifecycle, SpeakingMode
from .narration import NarrationConfig
from .voice import VoiceConfig


class Session(BaseModel):
    """
    Complete session state. This is the storage shape and the
    SessionStore.get() return type. API responses project this into
    SessionView (see views.py) for wire transmission — the projection
    can hide fields that are internal or computed-per-listener.
    """

    # ------------------------------------------------------------------
    # Identity — what is this session, where does it live.
    # ------------------------------------------------------------------

    session_id: str = Field(
        description="Stable UUID. Generated by Claude Code at session start.",
    )
    display_name: str = Field(
        description=(
            "User-facing name. Precedence: user-set persistent override > "
            "Claude Code /title custom title > VS Code panel label > "
            "slug-derived auto-name > catalog title > project_slug fallback."
        ),
    )
    cwd: Optional[str] = Field(
        default=None,
        description="Working directory at last hook fire. Used for cwd-based profile binding.",
    )
    project_dir: Optional[str] = Field(
        default=None,
        description=(
            "Claude Code's project directory name (e.g. "
            "'C--Users-brand-Dropbox-OCR-Open-Circuit-codetalker'). Survives "
            "session eviction; used as a workspace grouping fallback."
        ),
    )
    project_slug: Optional[str] = Field(
        default=None,
        description="Slug derived from project_dir's last segment. Coarser than project_dir.",
    )
    workspace_group: Optional[str] = Field(
        default=None,
        description=(
            "User-defined workspace bucket (e.g. 'OCRacing', 'OCDev'). "
            "Persistent overlay wins over auto-derive from display_name. "
            "Null means 'Ungrouped'."
        ),
    )
    workspace_group_source: Optional[Literal["user", "auto"]] = Field(
        default=None,
        description=(
            "Provenance of workspace_group. 'user' = explicitly set via "
            "PATCH; 'auto' or None = auto-derived from display_name. The "
            "read path respects 'user' verbatim (including empty string, "
            "which renders as the literal 'Ungrouped') so an explicit user "
            "choice survives display_name renames and 30s poll cycles."
        ),
    )

    # ------------------------------------------------------------------
    # Speaking behavior — how this session narrates.
    # ------------------------------------------------------------------

    active_mode: SpeakingMode = Field(
        default="brief",
        description=(
            "Speaking mode. live = continuous prose with cadence; "
            "brief = short summaries on significant events; "
            "direct = tool-output as-spoken, no LLM rewrite."
        ),
    )
    cadence: Optional[Cadence] = Field(
        default=None,
        description=(
            "Only meaningful when active_mode == 'live'. Strategy that "
            "decides when mid-response narration fires. None means "
            "'inherit from master config'."
        ),
    )
    enabled: bool = Field(
        default=True,
        description=(
            "Per-session mute. False = no TTS produced for this session "
            "regardless of master config. The user toggles this from "
            "Sessions list rows or SessionDetail. Distinct from master "
            "narration which silences the whole fleet."
        ),
    )
    auto_mode_enabled: bool = Field(
        default=False,
        description=(
            "When True, the daemon flips active_mode between live and "
            "brief based on user interaction recency. Active within "
            "AUTO_MODE_IDLE_THRESHOLD_SEC (default 30) → live; otherwise "
            "→ brief. The user toggles this per-session."
        ),
    )

    # ------------------------------------------------------------------
    # Audio routing — where the narration physically plays.
    # ------------------------------------------------------------------

    audio_outputs: List[AudioOutput] = Field(
        default_factory=lambda: ["desktop"],
        description=(
            "Set of sinks (unordered) that receive this session's audio. "
            "Empty list = no audio plays anywhere. Multiple sinks all "
            "receive the same WAV simultaneously."
        ),
    )

    # ------------------------------------------------------------------
    # Voice + character — who's speaking.
    # ------------------------------------------------------------------

    voice: VoiceConfig = Field(
        default_factory=VoiceConfig,
        description="Per-session voice override. Inherits from master config when fields are unset.",
    )
    narration: NarrationConfig = Field(
        default_factory=NarrationConfig,
        description=(
            "How text is rendered before TTS — markup form treatments, "
            "file path handling, code block rendering. Replaces the "
            "legacy live_overlay nested dict."
        ),
    )
    attached_profile: Optional[str] = Field(
        default=None,
        description=(
            "Profile name (a complete cfg overlay bundle). When attached, "
            "the profile's cfg merges under the session's live_overlay."
        ),
    )
    attached_character: Optional[CharacterRef] = Field(
        default=None,
        description=(
            "Embedded character record. Includes mesh_path and emotive_states "
            "so the glasses HUD can render the avatar without a separate "
            "lookup. None when no character is attached."
        ),
    )

    # ------------------------------------------------------------------
    # Lifecycle — explicit state machine driven by the daemon.
    # ------------------------------------------------------------------

    lifecycle: SessionLifecycle = Field(
        default="DORMANT",
        description=(
            "Current lifecycle state. Daemon is the sole writer. Drives "
            "filter pills, character pose, and visibility decisions. "
            "Transitions are recorded as LifecycleChanged events."
        ),
    )

    # ------------------------------------------------------------------
    # Timestamps — used for recency filters and event ordering.
    # ------------------------------------------------------------------

    last_hook_at: float = Field(
        default=0.0,
        description="Epoch seconds of last CC hook fire. 0 = never.",
    )
    last_modified: float = Field(
        default=0.0,
        description=(
            "Epoch seconds of last transcript jsonl modification. "
            "Independent of last_hook_at — Claude Code writes transcript "
            "asynchronously, so this can lag last_hook_at by seconds."
        ),
    )
    last_user_interaction_at: float = Field(
        default=0.0,
        description=(
            "Epoch seconds of last UserPromptSubmit or buddy inject. "
            "Drives the LISTENING lifecycle state and auto_mode evaluator."
        ),
    )

    # ------------------------------------------------------------------
    # User preferences — sorting / pinning.
    # ------------------------------------------------------------------

    pinned: bool = Field(
        default=False,
        description=(
            "Pin-to-top within the session's workspace group on session "
            "lists. The user toggles from a row action; persisted in the "
            "overlay so it syncs across surfaces."
        ),
    )

    model_config = {
        # Forbid extra fields at the boundary so typos in PATCH requests
        # surface immediately. The cost of writing the schema once is
        # paid back every time a future field is added.
        "extra": "forbid",
    }
